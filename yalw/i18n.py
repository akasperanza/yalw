def system_language() -> str:
    for var in ("LC_ALL", "LC_MESSAGES", "LANGUAGE", "LANG"):
        value = os.environ.get(var, "")
        if value:
            code = value.split(":")[0][:2].lower()
            if code in STRINGS:
                return code
    code = (locale.getlocale()[0] or "")[:2].lower()
    return code if code in STRINGS else "en"


def resolve(setting: str) -> str:
    """``auto`` → the system language (or English), else the chosen code."""
    return setting if setting in STRINGS else system_language()


def strings(setting: str) -> dict[str, str]:
    """All strings for ``setting``, falling back to English per key."""
    return {**STRINGS["en"], **STRINGS[resolve(setting)]}
